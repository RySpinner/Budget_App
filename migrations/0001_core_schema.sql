-- 0001_core_schema.sql
-- Core tables for the household spending tracker (SPEC.md section 4).
--
-- Conventions:
--   * Money is BIGINT cents. Positive = spending, negative = refund/credit.
--   * Dates are DATE (no times, no time zones).
--   * Running totals and budget-to-date are NOT stored here; they are
--     computed in views/queries (added in a later migration).

------------------------------------------------------------------------
-- Shared helper: keep updated_at current on every UPDATE.
------------------------------------------------------------------------
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

------------------------------------------------------------------------
-- people
------------------------------------------------------------------------
CREATE TABLE people (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

------------------------------------------------------------------------
-- cards
------------------------------------------------------------------------
CREATE TABLE cards (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name    TEXT NOT NULL UNIQUE CHECK (btrim(display_name) <> ''),
    issuer          TEXT NOT NULL,
    last4           CHAR(4) CHECK (last4 ~ '^[0-9]{4}$'),
    owner_person_id INTEGER NOT NULL REFERENCES people (id),
    parser_key      TEXT NOT NULL,          -- which parser module reads this card's CSV
    active          BOOLEAN NOT NULL DEFAULT true
);

------------------------------------------------------------------------
-- categories: two-level tree in one table.
--   parent_id IS NULL  -> top-level category (e.g. "Transportation")
--   parent_id NOT NULL -> subcategory (e.g. "Fuel"); its parent must be top-level.
------------------------------------------------------------------------
CREATE TABLE categories (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL CHECK (btrim(name) <> ''),
    parent_id  INTEGER REFERENCES categories (id),
    sort_order INTEGER NOT NULL DEFAULT 0,
    active     BOOLEAN NOT NULL DEFAULT true,
    CHECK (parent_id IS DISTINCT FROM id),
    -- Names are unique among siblings; NULLS NOT DISTINCT makes this also
    -- apply to top-level categories (which all have parent_id NULL).
    UNIQUE NULLS NOT DISTINCT (parent_id, name)
);

-- Enforce the two-level shape: a subcategory's parent must be top-level,
-- and a category that has children cannot itself become a subcategory.
CREATE FUNCTION check_category_tree() RETURNS trigger AS $$
BEGIN
    IF NEW.parent_id IS NOT NULL THEN
        IF EXISTS (SELECT 1 FROM categories WHERE id = NEW.parent_id AND parent_id IS NOT NULL) THEN
            RAISE EXCEPTION 'Category % cannot be nested under a subcategory (only two levels allowed)', NEW.name;
        END IF;
        IF EXISTS (SELECT 1 FROM categories WHERE parent_id = NEW.id) THEN
            RAISE EXCEPTION 'Category % has subcategories, so it must stay top-level', NEW.name;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER categories_check_tree
    BEFORE INSERT OR UPDATE OF parent_id ON categories
    FOR EACH ROW EXECUTE FUNCTION check_category_tree();

-- Reusable checks used by triggers on other tables.
CREATE FUNCTION is_subcategory(cat_id INTEGER) RETURNS BOOLEAN AS $$
    SELECT EXISTS (SELECT 1 FROM categories WHERE id = cat_id AND parent_id IS NOT NULL);
$$ LANGUAGE sql STABLE;

CREATE FUNCTION is_top_level_category(cat_id INTEGER) RETURNS BOOLEAN AS $$
    SELECT EXISTS (SELECT 1 FROM categories WHERE id = cat_id AND parent_id IS NULL);
$$ LANGUAGE sql STABLE;

-- Trigger: the row's category_id (if set) must be a subcategory.
CREATE FUNCTION require_subcategory() RETURNS trigger AS $$
BEGIN
    IF NEW.category_id IS NOT NULL AND NOT is_subcategory(NEW.category_id) THEN
        RAISE EXCEPTION '% must point at a subcategory, not a top-level category (category_id=%)',
            TG_TABLE_NAME, NEW.category_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

------------------------------------------------------------------------
-- import_batches: one row per uploaded CSV file.
-- The original file is archived on disk, named by batch id.
------------------------------------------------------------------------
CREATE TABLE import_batches (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id        INTEGER NOT NULL REFERENCES cards (id),
    filename       TEXT NOT NULL,
    file_sha256    CHAR(64) NOT NULL CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
    imported_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    rows_in_file   INTEGER NOT NULL CHECK (rows_in_file >= 0),
    rows_inserted  INTEGER NOT NULL CHECK (rows_inserted >= 0),
    rows_duplicate INTEGER NOT NULL CHECK (rows_duplicate >= 0),
    rows_excluded  INTEGER NOT NULL CHECK (rows_excluded >= 0),
    reverted_at    TIMESTAMPTZ          -- NULL unless the batch was undone
);

-- Not unique: re-importing a file after undoing it is allowed. The app
-- uses this index to warn "you already imported this exact file".
CREATE INDEX import_batches_file_sha256_idx ON import_batches (file_sha256);

------------------------------------------------------------------------
-- rules: categorization rules, applied in priority order (lowest first).
------------------------------------------------------------------------
CREATE TABLE rules (
    id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority                   INTEGER NOT NULL DEFAULT 100,
    match_type                 TEXT NOT NULL CHECK (match_type IN ('contains', 'exact', 'regex')),
    pattern                    TEXT NOT NULL CHECK (pattern <> ''),  -- matched case-insensitively against raw_description
    card_id                    INTEGER REFERENCES cards (id),        -- optional: only apply to this card
    min_amount_cents           BIGINT,                               -- optional amount range (inclusive)
    max_amount_cents           BIGINT,
    category_id                INTEGER NOT NULL REFERENCES categories (id),
    merchant_name              TEXT,                                 -- optional cleaned name to apply
    active                     BOOLEAN NOT NULL DEFAULT true,
    created_from_transaction_id INTEGER,                             -- FK added below (transactions not created yet)
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (min_amount_cents IS NULL OR max_amount_cents IS NULL OR min_amount_cents <= max_amount_cents)
);

CREATE TRIGGER rules_require_subcategory
    BEFORE INSERT OR UPDATE OF category_id ON rules
    FOR EACH ROW EXECUTE FUNCTION require_subcategory();

CREATE TRIGGER rules_set_updated_at
    BEFORE UPDATE ON rules
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

------------------------------------------------------------------------
-- transactions: the one table everything else is derived from.
------------------------------------------------------------------------
CREATE TABLE transactions (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source          TEXT NOT NULL CHECK (source IN ('card', 'manual')),
    card_id         INTEGER REFERENCES cards (id),
    txn_date        DATE,                -- NULL if the CSV doesn't provide it
    posted_date     DATE,                -- NULL for manual entries
    effective_date  DATE GENERATED ALWAYS AS (COALESCE(txn_date, posted_date)) STORED,
    amount_cents    BIGINT NOT NULL,     -- positive = spend, negative = refund
    raw_description TEXT NOT NULL,       -- exactly as the bank wrote it
    merchant        TEXT,                -- cleaned display name
    category_id     INTEGER REFERENCES categories (id),  -- NULL = uncategorized (review queue)
    category_source TEXT CHECK (category_source IN ('rule', 'manual')),
    rule_id         INTEGER REFERENCES rules (id) ON DELETE SET NULL,
    purchaser_id    INTEGER NOT NULL REFERENCES people (id),
    note            TEXT,
    fingerprint     TEXT UNIQUE,         -- dedup key for card rows (SPEC section 5)
    import_batch_id INTEGER REFERENCES import_batches (id),
    raw_row         JSONB,               -- original CSV row
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Every transaction needs a date to land in a month.
    CONSTRAINT transactions_has_a_date CHECK (txn_date IS NOT NULL OR posted_date IS NOT NULL),
    -- Card rows have a card, a batch and a fingerprint; manual rows have none of these.
    CONSTRAINT transactions_card_fields CHECK (
        (source = 'card'   AND card_id IS NOT NULL AND import_batch_id IS NOT NULL AND fingerprint IS NOT NULL)
     OR (source = 'manual' AND card_id IS NULL     AND import_batch_id IS NULL     AND posted_date IS NULL)
    ),
    -- A category always records who chose it, and only categorized rows have a source.
    CONSTRAINT transactions_category_source CHECK ((category_id IS NULL) = (category_source IS NULL)),
    -- rule_id is only meaningful when a rule assigned the category.
    CONSTRAINT transactions_rule_id CHECK (rule_id IS NULL OR category_source = 'rule')
);

CREATE INDEX transactions_effective_date_idx ON transactions (effective_date);
CREATE INDEX transactions_category_id_idx    ON transactions (category_id);
CREATE INDEX transactions_import_batch_idx   ON transactions (import_batch_id);
CREATE INDEX transactions_uncategorized_idx  ON transactions (effective_date) WHERE category_id IS NULL;

ALTER TABLE rules
    ADD CONSTRAINT rules_created_from_transaction_fk
    FOREIGN KEY (created_from_transaction_id) REFERENCES transactions (id) ON DELETE SET NULL;

CREATE TRIGGER transactions_require_subcategory
    BEFORE INSERT OR UPDATE OF category_id ON transactions
    FOR EACH ROW EXECUTE FUNCTION require_subcategory();

CREATE TRIGGER transactions_set_updated_at
    BEFORE UPDATE ON transactions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Non-negotiable (SPEC section 6): a rule must never overwrite a manual choice.
-- The rules engine already filters these rows out; this is a safety net.
CREATE FUNCTION protect_manual_category() RETURNS trigger AS $$
BEGIN
    IF OLD.category_source = 'manual' AND NEW.category_source = 'rule' THEN
        RAISE EXCEPTION 'Transaction % was categorized manually; a rule may not overwrite it', OLD.id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER transactions_protect_manual_category
    BEFORE UPDATE OF category_id, category_source ON transactions
    FOR EACH ROW EXECUTE FUNCTION protect_manual_category();

------------------------------------------------------------------------
-- splits: optional; when present, reports use these lines instead of
-- the parent's category. Lines must sum exactly to the parent amount.
------------------------------------------------------------------------
CREATE TABLE splits (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id INTEGER NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    amount_cents   BIGINT NOT NULL,
    category_id    INTEGER NOT NULL REFERENCES categories (id),
    note           TEXT
);

CREATE INDEX splits_transaction_id_idx ON splits (transaction_id);

CREATE TRIGGER splits_require_subcategory
    BEFORE INSERT OR UPDATE OF category_id ON splits
    FOR EACH ROW EXECUTE FUNCTION require_subcategory();

-- Sum check. It runs at COMMIT (deferred), so the app can delete and
-- re-insert all split lines for a transaction inside one transaction.
CREATE FUNCTION check_split_total(txn_id INTEGER) RETURNS void AS $$
DECLARE
    parent_amount BIGINT;
    split_total   BIGINT;
    split_count   INTEGER;
BEGIN
    SELECT amount_cents INTO parent_amount FROM transactions WHERE id = txn_id;
    IF NOT FOUND THEN
        RETURN;  -- parent was deleted; its splits cascade away
    END IF;
    SELECT COALESCE(SUM(amount_cents), 0), COUNT(*) INTO split_total, split_count
      FROM splits WHERE transaction_id = txn_id;
    IF split_count > 0 AND split_total <> parent_amount THEN
        RAISE EXCEPTION 'Splits for transaction % add up to % cents but the transaction is % cents',
            txn_id, split_total, parent_amount;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION splits_check_total_trigger() RETURNS trigger AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM check_split_total(OLD.transaction_id);
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM check_split_total(NEW.transaction_id);
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER splits_check_total
    AFTER INSERT OR UPDATE OR DELETE ON splits
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION splits_check_total_trigger();

CREATE FUNCTION transactions_check_split_total_trigger() RETURNS trigger AS $$
BEGIN
    PERFORM check_split_total(NEW.id);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- Changing a split transaction's amount must keep the splits consistent too.
CREATE CONSTRAINT TRIGGER transactions_check_split_total
    AFTER UPDATE OF amount_cents ON transactions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION transactions_check_split_total_trigger();

------------------------------------------------------------------------
-- budgets: monthly budget per top-level category, effective from a month.
-- The budget for a month is the row with the latest effective_from on or
-- before that month, so changing a budget never rewrites history.
------------------------------------------------------------------------
CREATE TABLE budgets (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id          INTEGER NOT NULL REFERENCES categories (id),
    monthly_amount_cents BIGINT NOT NULL CHECK (monthly_amount_cents >= 0),
    effective_from       DATE NOT NULL CHECK (EXTRACT(DAY FROM effective_from) = 1),  -- first of a month
    UNIQUE (category_id, effective_from)
);

CREATE FUNCTION require_top_level_category() RETURNS trigger AS $$
BEGIN
    IF NOT is_top_level_category(NEW.category_id) THEN
        RAISE EXCEPTION 'Budgets are set on top-level categories (category_id=% is a subcategory)', NEW.category_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER budgets_require_top_level
    BEFORE INSERT OR UPDATE OF category_id ON budgets
    FOR EACH ROW EXECUTE FUNCTION require_top_level_category();

