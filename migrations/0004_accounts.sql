    CHECK (transfer_id IS NULL OR kind = 'transfer');

-- The category's kind must match the transaction's kind (an income category on an income row).
CREATE OR REPLACE FUNCTION require_subcategory() RETURNS trigger AS $$
DECLARE
    cat_kind TEXT;
BEGIN
    IF NEW.category_id IS NOT NULL THEN
        IF NOT is_subcategory(NEW.category_id) THEN
            RAISE EXCEPTION '% must point at a subcategory, not a top-level category (category_id=%)',
                TG_TABLE_NAME, NEW.category_id;
        END IF;
        IF TG_TABLE_NAME = 'transactions' THEN
            SELECT kind INTO cat_kind FROM categories WHERE id = NEW.category_id;
            IF cat_kind IS DISTINCT FROM NEW.kind THEN
                RAISE EXCEPTION 'Transaction % is kind % but category % is an % category',
                    NEW.id, NEW.kind, NEW.category_id, cat_kind;
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER transactions_require_subcategory ON transactions;
CREATE TRIGGER transactions_require_subcategory
    BEFORE INSERT OR UPDATE OF category_id, kind ON transactions
    FOR EACH ROW EXECUTE FUNCTION require_subcategory();

-- Manual kinds are protected from rules, like manual categories.
CREATE OR REPLACE FUNCTION protect_manual_category() RETURNS trigger AS $$
BEGIN
    IF OLD.category_source = 'manual' AND NEW.category_source = 'rule' THEN
        RAISE EXCEPTION 'Transaction % was categorized manually; a rule may not overwrite it', OLD.id;
    END IF;
    IF OLD.kind_source = 'manual' AND NEW.kind_source = 'rule' THEN
        RAISE EXCEPTION 'Transaction %''s kind was set manually; a rule may not overwrite it', OLD.id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER transactions_protect_manual_category ON transactions;
CREATE TRIGGER transactions_protect_manual_category
    BEFORE UPDATE OF category_id, category_source, kind, kind_source ON transactions
    FOR EACH ROW EXECUTE FUNCTION protect_manual_category();

-- Splits only on expense/income rows, in categories of the same kind.
CREATE FUNCTION splits_check_kind() RETURNS trigger AS $$
DECLARE
    parent_kind TEXT;
    cat_kind TEXT;
BEGIN
    SELECT kind INTO parent_kind FROM transactions WHERE id = NEW.transaction_id;
    SELECT kind INTO cat_kind FROM categories WHERE id = NEW.category_id;
    IF parent_kind IS DISTINCT FROM cat_kind THEN
        RAISE EXCEPTION 'Split category kind (%) must match the transaction kind (%)', cat_kind, parent_kind;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER splits_check_kind
    BEFORE INSERT OR UPDATE OF category_id, transaction_id ON splits
    FOR EACH ROW EXECUTE FUNCTION splits_check_kind();

------------------------------------------------------------------------
-- Transfer integrity (checked at COMMIT, so both legs can be linked in
-- one database transaction): a transfer has exactly two legs, in
-- different accounts, summing to zero.
------------------------------------------------------------------------
CREATE FUNCTION check_transfer(tid INTEGER) RETURNS void AS $$
DECLARE
    legs INTEGER;
    total BIGINT;
    accounts_used INTEGER;
BEGIN
    IF tid IS NULL OR NOT EXISTS (SELECT 1 FROM transfers WHERE id = tid) THEN
        RETURN;
    END IF;
    SELECT count(*), COALESCE(sum(amount_cents), 0), count(DISTINCT account_id)
      INTO legs, total, accounts_used
      FROM transactions WHERE transfer_id = tid;
    IF legs <> 2 THEN
        RAISE EXCEPTION 'Transfer % has % legs; it needs exactly 2', tid, legs;
    END IF;
    IF accounts_used <> 2 THEN
        RAISE EXCEPTION 'Transfer % has both legs in the same account', tid;
    END IF;
    IF total <> 0 THEN
        RAISE EXCEPTION 'Transfer % legs add up to % cents; they must cancel out to 0', tid, total;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION transactions_check_transfer_trigger() RETURNS trigger AS $$
BEGIN
    -- Deletes aren't checked here: deleting a leg always dissolves its transfer
    -- (transactions_dissolve_transfer below), whichever trigger runs first.
    IF TG_OP = 'UPDATE' THEN
        PERFORM check_transfer(OLD.transfer_id);
    END IF;
    PERFORM check_transfer(NEW.transfer_id);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER transactions_check_transfer
    AFTER INSERT OR UPDATE OF transfer_id, amount_cents, account_id ON transactions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION transactions_check_transfer_trigger();

-- Deleting one leg (e.g. undoing an import) dissolves the transfer, so the
-- other leg becomes unmatched instead of breaking the rule above.
CREATE FUNCTION transactions_dissolve_transfer() RETURNS trigger AS $$
BEGIN
    IF OLD.transfer_id IS NOT NULL THEN
        DELETE FROM transfers WHERE id = OLD.transfer_id;
    END IF;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER transactions_dissolve_transfer
    AFTER DELETE ON transactions
    FOR EACH ROW EXECUTE FUNCTION transactions_dissolve_transfer();

------------------------------------------------------------------------
-- balance_snapshots: balances as the bank states them (facts, never computed)
------------------------------------------------------------------------
CREATE TABLE balance_snapshots (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    INTEGER NOT NULL REFERENCES accounts (id),
    as_of_date    DATE NOT NULL,
    balance_cents BIGINT NOT NULL,     -- held (assets) or owed (liabilities)
    source        TEXT NOT NULL CHECK (source IN ('import', 'statement', 'manual')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (account_id, as_of_date, source)
);

------------------------------------------------------------------------
-- Views. transaction_lines: every transaction (split lines flattened), any
-- kind. spending_lines: the expense part only; spending reports read it, so
-- transfers and income never count as spending.
------------------------------------------------------------------------
DROP VIEW monthly_totals;
DROP VIEW spending_lines;

CREATE VIEW transaction_lines AS
WITH lines AS (
    SELECT t.id AS transaction_id, NULL::integer AS split_id, t.amount_cents, t.category_id, t.note
      FROM transactions t
     WHERE NOT EXISTS (SELECT 1 FROM splits s WHERE s.transaction_id = t.id)
    UNION ALL
    SELECT s.transaction_id, s.id, s.amount_cents, s.category_id, s.note
      FROM splits s
)
SELECT l.transaction_id,
       l.split_id,
       (SELECT count(*) FROM splits s WHERE s.transaction_id = t.id) AS split_count,
       t.source,
       t.kind,
       t.transfer_id,
       t.effective_date,
       date_trunc('month', t.effective_date)::date AS month,
       l.amount_cents,
       l.category_id,
       sub.name       AS subcategory,
       top.id         AS top_category_id,
       top.name       AS top_category,
       t.merchant,
       t.raw_description,
       t.account_id,
       a.display_name AS account,
       t.purchaser_id,
       p.name         AS purchaser,
       l.note
  FROM lines l
  JOIN transactions t      ON t.id = l.transaction_id
  JOIN accounts a          ON a.id = t.account_id
  JOIN people p            ON p.id = t.purchaser_id
  LEFT JOIN categories sub ON sub.id = l.category_id
  LEFT JOIN categories top ON top.id = sub.parent_id;

CREATE VIEW spending_lines AS
SELECT * FROM transaction_lines WHERE kind = 'expense';

CREATE VIEW monthly_totals AS
SELECT month,
       top_category_id,
       category_id,
       sum(amount_cents)::bigint AS amount_cents,
       count(*)                  AS line_count
  FROM spending_lines
 GROUP BY month, top_category_id, category_id;
