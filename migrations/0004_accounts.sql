------------------------------------------------------------------------
-- categories: expense or income (set on the top level, inherited below)
------------------------------------------------------------------------
ALTER TABLE categories ADD COLUMN kind TEXT NOT NULL DEFAULT 'expense' CHECK (kind IN ('expense', 'income'));

CREATE FUNCTION categories_inherit_kind() RETURNS trigger AS $$
BEGIN
    IF NEW.parent_id IS NOT NULL THEN
        SELECT kind INTO NEW.kind FROM categories WHERE id = NEW.parent_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER categories_inherit_kind
    BEFORE INSERT OR UPDATE OF parent_id, kind ON categories
    FOR EACH ROW EXECUTE FUNCTION categories_inherit_kind();

CREATE FUNCTION categories_cascade_kind() RETURNS trigger AS $$
BEGIN
    UPDATE categories SET kind = NEW.kind WHERE parent_id = NEW.id AND kind <> NEW.kind;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER categories_cascade_kind
    AFTER UPDATE OF kind ON categories
    FOR EACH ROW WHEN (NEW.parent_id IS NULL) EXECUTE FUNCTION categories_cascade_kind();

-- Budgets: top-level EXPENSE categories only.
CREATE OR REPLACE FUNCTION require_top_level_category() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM categories WHERE id = NEW.category_id AND parent_id IS NULL AND kind = 'expense') THEN
        RAISE EXCEPTION 'Budgets are set on top-level expense categories (category_id=%)', NEW.category_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

