-- 0004_accounts.sql
-- v2 foundation (SPEC.md phase 8): cards become generic accounts; every
-- transaction gets a kind (expense / income / transfer); transfers link two
-- legs that must sum to zero; categories get a kind; balance snapshots.
--
-- Existing data is kept: card ids become account ids unchanged (so import
-- fingerprints still match), card rows become kind 'expense', and manual
-- entries move into a new built-in "Cash" account.

